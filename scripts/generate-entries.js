'use strict';
const fs = require('node:fs');
const path = require('node:path');
const names = require('./exports.json');
const sourcePath = require('./source-path.js');
const { root, consumerManifest } = require('./package-layout');

module.exports = function generateEntries(destination) {
  destination = path.resolve(destination);
  if (
    path.dirname(destination) !== root ||
    !path.basename(destination).startsWith('.go-types-build-') ||
    fs.lstatSync(destination).isSymbolicLink() ||
    path.dirname(fs.realpathSync(destination)) !== fs.realpathSync(root)
  ) {
    throw Error('Entries must be generated inside an owned package staging directory');
  }
  const write = (name, text) => fs.writeFileSync(path.join(destination, name), text);
  if (new Set(names).size !== names.length || names.some((name) => !/^[A-Za-z][A-Za-z0-9]*$/.test(name))) {
    throw new TypeError('Export names must be unique JavaScript identifiers.');
  }
  for (const name of names) {
    if (!fs.existsSync(path.join(destination, sourcePath(name)))) throw Error('Missing export implementation: ' + name);
  }
  for (const dir of ['esm', 'types']) fs.mkdirSync(path.join(destination, dir), { recursive: true });
  write(
    'index.js',
    "'use strict';\n\n" +
      names.map((name) => 'exports.' + name + " = require('./" + sourcePath(name) + "');").join('\n') +
      '\n'
  );
  write(
    'index.mjs',
    '// Named exports expose individual modules to bundlers. Function identities remain shared.\n' +
      names.map((name) => 'export { default as ' + name + " } from './" + sourcePath(name) + "';").join('\n') +
      "\nexport { default } from './index.js';\n"
  );
  write(
    'index.d.mts',
    "import Types from './index.js';\nexport default Types;\nexport { " +
      names.join(', ') +
      " } from './index.js';\nexport type { TypeName, TypeMatcher, TypeGuard, TypedArray, ConversionCondition, ArrayElement, Boxed, Unboxed, ConvertedMap, ConvertedPlainObject, ConvertedSet } from './index.js';\n"
  );
  const exportsMap = {
    '.': {
      import: { types: './index.d.mts', default: './index.mjs' },
      require: { types: './index.d.ts', default: './index.js' },
      default: './index.js'
    }
  };
  const legacyTypePaths = {};
  for (const name of names) {
    write('esm/' + name + '.mjs', 'export { default, default as ' + name + " } from '../" + sourcePath(name) + "';\n");
    write(
      'types/' + name + '.d.ts',
      "import Types = require('../index.js');\ndeclare const check: typeof Types." + name + ';\nexport = check;\n'
    );
    write('types/' + name + '.d.mts', 'export { ' + name + ' as default, ' + name + " } from '../index.js';\n");
    const target = {
      import: { types: './types/' + name + '.d.mts', default: './esm/' + name + '.mjs' },
      require: { types: './types/' + name + '.d.ts', default: './' + sourcePath(name) },
      default: './' + sourcePath(name)
    };
    const aliases = ['./' + name, './src/' + name, './src/' + name + '.js'];
    if (sourcePath(name).startsWith('src/conversion/'))
      aliases.push(
        './conversion/' + name,
        './conversion/' + name + '.js',
        './src/conversion/' + name,
        './src/conversion/' + name + '.js'
      );
    for (const alias of aliases) {
      exportsMap[alias] = target;
      legacyTypePaths[alias.slice(2)] = ['types/' + name + '.d.ts'];
    }
    // Node 8 follows physical paths; every alias shares its individual implementation.
    for (const entry of new Set(aliases.map((alias) => alias.slice(2).replace(/\.js$/, '') + '.js'))) {
      if (entry === sourcePath(name)) continue;
      const relative = path.posix.relative(path.posix.dirname(entry), sourcePath(name));
      const request = relative.startsWith('.') ? relative : './' + relative;
      fs.mkdirSync(path.dirname(path.join(destination, entry)), { recursive: true });
      write(
        entry,
        "'use strict';\n// Generated by scripts/generate-entries.js.\nmodule.exports = require(" +
          JSON.stringify(request) +
          ');\n'
      );
    }
  }
  exportsMap['./package.json'] = './package.json';
  // Native ESM exposes only the default API object when importing a CommonJS bundle.
  write('types/bundle.d.mts', "import Types from '../index.js';\nexport default Types;\n");
  for (const file of ['go-types.js', 'go-types.min.js']) {
    const target = './dist/' + file;
    exportsMap[target] = {
      import: { types: './types/bundle.d.mts', default: target },
      require: { types: './index.d.ts', default: target },
      default: target
    };
    legacyTypePaths['dist/' + file] = ['index.d.ts'];
  }
  exportsMap['./dist/go-types.mjs'] = { types: './index.d.mts', default: './dist/go-types.mjs' };
  legacyTypePaths['dist/go-types.mjs'] = ['index.d.mts'];
  // Node 13.0 recognises exports arrays but needs a literal fallback before conditional exports support.
  for (const [alias, target] of Object.entries(exportsMap)) {
    if (target && typeof target === 'object') exportsMap[alias] = [target, target.default];
  }
  const pkg = consumerManifest({ typesVersions: { '*': legacyTypePaths }, exports: exportsMap });
  write('package.json', JSON.stringify(pkg, null, 2) + '\n');
  return pkg;
};
if (require.main === module) throw Error('Entry generation is internal; use npm run build for a complete package.');
